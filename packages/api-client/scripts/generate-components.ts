import { readFile, writeFile } from 'node:fs/promises';

const spec = JSON.parse(await readFile('../../apps/api/openapi.json', 'utf8')) as {
  components: { schemas: Record<string, unknown> };
};
const schemaNames = Object.keys(spec.components.schemas).sort();
const output = `// This file is auto-generated by scripts/generate-components.ts\n\nimport type {\n${schemaNames.map((name) => `  ${name},`).join('\n')}\n} from './types.gen';\n\nexport type components = {\n  schemas: {\n${schemaNames.map((name) => `    ${name}: ${name};`).join('\n')}\n  };\n};\n`;

await writeFile('src/generated/components.gen.ts', output);
