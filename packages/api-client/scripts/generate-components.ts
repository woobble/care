import { readFile, writeFile } from 'node:fs/promises';

const spec = JSON.parse(await readFile('../../apps/api/openapi.json', 'utf8')) as {
  components: { schemas: Record<string, unknown> };
  paths: Record<string, Record<string, { operationId?: string }>>;
};
const schemaNames = Object.keys(spec.components.schemas).sort();
const output = `// This file is auto-generated by scripts/generate-components.ts\n\nimport type {\n${schemaNames.map((name) => `  ${name},`).join('\n')}\n} from './types.gen';\n\nexport type components = {\n  schemas: {\n${schemaNames.map((name) => `    ${name}: ${name};`).join('\n')}\n  };\n};\n`;

await writeFile('src/generated/components.gen.ts', output);

const operationName = (operationId: string) =>
  operationId
    .split(/[_-]/)
    .filter(Boolean)
    .map((part, index) =>
      index === 0 ? part[0].toLowerCase() + part.slice(1) : part[0].toUpperCase() + part.slice(1),
    )
    .join('');

const methods = new Set(['get', 'post', 'put', 'patch', 'delete']);
const sdkSource = await readFile('src/generated/sdk.gen.ts', 'utf8');
const sdkOperations = new Set(
  [...sdkSource.matchAll(/export const (\w+)/g)].map(([, name]) => name),
);
const routeOperations = Object.entries(spec.paths)
  .sort(([left], [right]) => left.localeCompare(right))
  .map(([path, operations]) => {
    const routeMethods = Object.entries(operations)
      .filter(([method]) => methods.has(method))
      .sort(([left], [right]) => left.localeCompare(right))
      .map(([method, operation]) => {
        if (!operation.operationId) {
          throw new Error(`Missing operationId for ${method.toUpperCase()} ${path}`);
        }
        const name = operationName(operation.operationId);
        if (!sdkOperations.has(name)) {
          throw new Error(`No generated SDK operation ${name} for ${method.toUpperCase()} ${path}`);
        }
        return `    ${method}: ${JSON.stringify(name)},`;
      });
    return `  ${JSON.stringify(path)}: {\n${routeMethods.join('\n')}\n  },`;
  });

const routes = `// This file is auto-generated by scripts/generate-components.ts\n\nexport const routeOperations = {\n${routeOperations.join('\n')}\n} as const;\n`;
await writeFile('src/generated/routes.gen.ts', routes);

// The generated transport helpers are not compatible with exact optional property checking.
for (const path of [
  'src/generated/client/client.gen.ts',
  'src/generated/client/utils.gen.ts',
  'src/generated/core/params.gen.ts',
  'src/generated/core/pathSerializer.gen.ts',
  'src/generated/core/serverSentEvents.gen.ts',
]) {
  // oxlint-disable-next-line no-await-in-loop -- Preserve sequential file and process operations.
  const generated = await readFile(path, 'utf8');
  const header = '// This file is auto-generated by @hey-api/openapi-ts';
  if (!generated.startsWith(`${header}\n`)) {
    throw new Error(`Unexpected generated file header: ${path}`);
  }
  if (!generated.startsWith(`${header}\n// @ts-nocheck\n`)) {
    // oxlint-disable-next-line no-await-in-loop -- Preserve sequential file and process operations.
    await writeFile(path, generated.replace(header, `${header}\n// @ts-nocheck`));
  }
}
